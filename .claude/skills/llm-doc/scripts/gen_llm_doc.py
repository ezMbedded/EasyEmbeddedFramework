#!/usr/bin/env python3
"""Generate compact, LLM-friendly API markdown from Doxygen XML output.

Usage (from the repository root, after running doxygen):
    python3 .claude/skills/llm-doc/scripts/gen_llm_doc.py                 # every public header
    python3 .claude/skills/llm-doc/scripts/gen_llm_doc.py inc/service/event_bus/ez_event_bus.h
                                                                           # only this header

With header arguments only those headers are parsed and written; INDEX.md is
updated for them and the other modules stay as they are. The coverage check
is skipped.

Defaults: --xml doxygen/xml  --out docs_llm/api  --inc inc

Produces:
    <out>/<module>.md   one cheat sheet per public header (.h and .hpp)
    <out>/INDEX.md      module table (linked from LLM_GUIDE.md section 5)

Exit codes: 0 ok, 1 headers failed or (full run) headers under --inc without a
cheat sheet, 2 fatal error.

Doxygen config required:  GENERATE_XML = YES,  XML_PROGRAMLISTING = YES
Document the context properties with custom aliases so they are machine-readable, e.g. in the Doxyfile:
    ALIASES += "isr_safe{1}=@par ISR-safe:^^\1"
    ALIASES += "blocking{1}=@par Blocking:^^\1"
Anything rendered as a "par" section is picked up under its title and written
as plain text (e.g. "- ISR-safe: yes") so that it can be searched literally.
"""
import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HEADER_SUFFIXES = (".h", ".hpp")
BANNER = "<!-- GENERATED by .claude/skills/llm-doc/scripts/gen_llm_doc.py. Do not edit. -->"

# simplesect kinds shown in the cheat sheet, in order
SECTION_ORDER = ["pre", "post", "warning", "note", "remark", "see"]
SECTION_TITLE = {"pre": "Pre", "post": "Post", "warning": "Warning",
                 "note": "Note", "remark": "Remark", "see": "See"}


def text(el):
    """Flatten an element to plain text, honouring Doxygen's <sp/>."""
    if el is None:
        return ""
    parts = [el.text or ""]
    for ch in el:
        parts.append(" " if ch.tag == "sp" else text(ch))
        parts.append(ch.tail or "")
    return "".join(parts)


def paras(el):
    """Text of each <para> directly under el, skipping nested structures."""
    if el is None:
        return []
    out = []
    for p in el.findall("para"):
        # text of the para without the special sections/lists/code blocks
        buf = [p.text or ""]
        for ch in p:
            if ch.tag not in ("simplesect", "parameterlist", "programlisting"):
                buf.append(" " if ch.tag == "sp" else text(ch))
            buf.append(ch.tail or "")
        s = " ".join("".join(buf).split())
        # "\b Example" only labels the code block, which is rendered separately
        if s and s != "Example":
            out.append(s)
    return out


def all_in(el, tag):
    return [] if el is None else list(el.iter(tag))


def template_prefix(el):
    """'template <typename T> ' of a C++ template class or member, else ''."""
    tpl = el.find("templateparamlist")
    if tpl is None:
        return ""
    params = [" ".join(text(p.find("type")).split()) for p in tpl.findall("param")]
    return f"template <{', '.join(params)}> "


def signature(m):
    """One-line C/C++ signature."""
    ret = " ".join(text(m.find("type")).split())
    name = text(m.find("name")).strip()
    args = " ".join(text(m.find("argsstring")).split())
    pre = template_prefix(m)
    if m.get("static") == "yes":
        pre += "static "
    if m.get("virt") == "virtual":
        pre += "virtual "
    return f"{pre}{ret} {name}{args}".strip()


def code_blocks(detail):
    blocks = []
    for pl in all_in(detail, "programlisting"):
        lines = [text(cl).rstrip() for cl in pl.findall("codeline")]
        blocks.append("\n".join(lines).strip("\n"))
    return blocks


def render_function(m, scope="", lang="c"):
    brief = " ".join(text(m.find("briefdescription")).split())
    detail = m.find("detaileddescription")
    out = [f"### `{scope}{text(m.find('name')).strip()}`", "",
           f"```{lang}", signature(m) + ";", "```", ""]
    if brief:
        out += [brief, ""]
    for p in paras(detail):
        out += [p, ""]

    # parameters and return values
    for kind, title in (("param", "Parameters"), ("retval", "Return values")):
        items = []
        for pl in all_in(detail, "parameterlist"):
            if pl.get("kind") != kind:
                continue
            for it in pl.findall("parameteritem"):
                # "@param name: desc" makes doxygen keep the colon in the name
                names = ", ".join(" ".join(text(n).split()).rstrip(":")
                                  for n in it.iter("parametername"))
                desc = " ".join(" ".join(paras(it.find("parameterdescription"))).split())
                items.append(f"- `{names}`: {desc}")
        if items:
            out += [f"**{title}**", ""] + items + [""]

    # @return
    for ss in all_in(detail, "simplesect"):
        if ss.get("kind") == "return":
            out += [f"**Returns:** {' '.join(' '.join(paras(ss)).split())}", ""]

    # pre/post/warning/note/see and custom @par sections
    sections = {}
    custom = {}
    for ss in all_in(detail, "simplesect"):
        k = ss.get("kind")
        if k in SECTION_TITLE:
            sections.setdefault(SECTION_TITLE[k], []).append(
                " ".join(" ".join(paras(ss)).split()) or " ".join(text(ss).split()))
        elif k == "par":
            title = " ".join(text(ss.find("title")).split()).rstrip(":")
            custom.setdefault(title, []).append(" ".join(" ".join(paras(ss)).split()))
    for title in [SECTION_TITLE[k] for k in SECTION_ORDER]:
        for body in sections.get(title, []):
            out.append(f"- **{title}:** {body}")
    # custom tags are plain text so "ISR-safe: yes" can be matched literally
    for title, bodies in custom.items():
        for body in bodies:
            out.append(f"- {title}: {body}")
    if sections or custom:
        out.append("")

    for b in code_blocks(detail):
        out += ["**Example**", "", f"```{lang}", b, "```", ""]
    return out


def member_file(m):
    loc = m.find("location")
    return "" if loc is None else (loc.get("declfile") or loc.get("file", ""))


def in_file(m, loc):
    """True if the member is declared in the header `loc` (Doxygen file path)."""
    f = member_file(m)
    return not loc or f == loc or f.endswith("/" + loc) or loc.endswith("/" + f)


def render_other(cd, loc=None, lang="c", kinds=("enum", "typedef", "define")):
    """Enums, typedefs, macros (and optionally variables) as signatures only."""
    out = []
    for m in cd.iter("memberdef"):
        kind = m.get("kind")
        if kind not in kinds or m.get("prot", "public") != "public":
            continue
        if not in_file(m, loc):
            continue
        brief = " ".join(text(m.find("briefdescription")).split())
        name = text(m.find("name")).strip()
        if kind == "enum":
            vals = []
            for v in m.findall("enumvalue"):
                doc = " ".join(text(v.find("briefdescription")).split())
                if not doc:    # a /**< ... */ member comment is a detailed description
                    doc = " ".join(" ".join(paras(v.find("detaileddescription"))).split())
                vals.append((text(v.find("name")).strip(), doc))
            kw = "enum class" if m.get("strong") == "yes" else "enum"
            lines_ = [f"  {n}{',' if i < len(vals) - 1 else ''}" + (f"  /* {d} */" if d else "")
                      for i, (n, d) in enumerate(vals)]
            sig = f"{kw} {name} {{\n" + "\n".join(lines_) + "\n}"
        elif kind == "variable":
            sig = (" ".join(text(m.find("definition")).split())
                   + " ".join(text(m.find("argsstring")).split()) + ";")
        elif kind == "typedef":
            # A function-pointer typedef already has its parameters in the
            # definition, e.g. "void(* cb) (int x)". Appending argsstring
            # would print the parameter list twice.
            definition = " ".join(text(m.find("definition")).split())
            sig = definition if "(*" in definition else \
                  definition + " ".join(text(m.find("argsstring")).split())
        else:
            params = [text(p.find("defname")).strip() for p in m.findall("param")]
            sig = f"#define {name}" + (f"({', '.join(params)})" if params else "")
        out += [f"```{lang}", sig, "```", brief, ""] if brief else [f"```{lang}", sig, "```", ""]
    return out


def render_c_struct(c, listing=""):
    """A plain C struct/union with its data members and their comments."""
    kind = c.get("kind")
    name = text(c.find("compoundname")).strip()
    brief = " ".join(text(c.find("briefdescription")).split())
    fields = []
    for m in c.iter("memberdef"):
        if m.get("kind") != "variable" or m.get("prot", "public") != "public":
            continue
        definition = " ".join(text(m.find("definition")).split())
        args = " ".join(text(m.find("argsstring")).split())
        # an array field already has its [N] in the definition in some Doxygen versions
        decl = definition if (args and definition.endswith(args)) else definition + args
        # "struct ezDrvHandle ezI2cHandle_t::drv_handle" -> "struct ezDrvHandle drv_handle"
        decl = decl.replace(name + "::", "")
        doc = " ".join(text(m.find("briefdescription")).split())
        if not doc:    # a /**< ... */ member comment is a detailed description
            doc = " ".join(" ".join(paras(m.find("detaileddescription"))).split())
        fields.append(f"  {decl};" + (f"  /* {doc} */" if doc else ""))
    # "typedef struct { ... } name;" when the header declares it that way
    is_typedef = re.search(r"\}\s*" + re.escape(name) + r"\s*;", listing) is not None
    head = f"typedef {kind}" if is_typedef else f"{kind} {name}"
    tail = f"}} {name};" if is_typedef else "};"
    sig = f"{head} {{\n" + "\n".join(fields) + f"\n{tail}" if fields else f"{head} {{}} {name};"
    out = ["```c", sig, "```"]
    if brief:
        out.append(brief)
    out.append("")
    for p in paras(c.find("detaileddescription")):
        out += [p, ""]
    return out


def load_compound(xml_dir, refid):
    path = xml_dir / f"{refid}.xml"
    if not path.is_file():
        return None
    return ET.parse(path).getroot().find("compounddef")


def collect_namespaces(xml_dir, cd, seen=None):
    """Namespace compounds referenced by cd, recursively."""
    seen = {} if seen is None else seen
    for ref in cd.findall("innernamespace"):
        rid = ref.get("refid")
        if rid in seen:
            continue
        ns = load_compound(xml_dir, rid)
        if ns is not None:
            seen[rid] = ns
            collect_namespaces(xml_dir, ns, seen)
    return seen


def class_title(c):
    kind = "struct" if c.get("kind") == "struct" else "class"
    name = text(c.find("compoundname")).strip()
    return kind, name, template_prefix(c)


def render_class(xml_dir, c, loc, done, level=2):
    """Public API of a C++ class/struct, nested public types included."""
    out = []
    kind, name, tpl = class_title(c)
    done.add(c.get("id"))
    h = "#" * level
    out += [f"{h} {kind} `{name}`", "", "```cpp", f"{tpl}{kind} {name};", "```", ""]
    brief = " ".join(text(c.find("briefdescription")).split())
    if brief:
        out += [brief, ""]
    for p in paras(c.find("detaileddescription")):
        out += [p, ""]
    other = render_other(c, None, "cpp", ("enum", "typedef", "variable"))
    if other:
        out += [f"{h}# Types and data members of `{name}`", ""] + other
    funcs = [m for m in c.iter("memberdef") if m.get("kind") == "function"
             and m.get("prot", "public") == "public"
             and "delete" not in text(m.find("argsstring")).replace(" ", "").split("=")[-1:]]
    count = len(funcs)
    scope = name.split("::")[-1] + "::"
    for m in funcs:
        out += render_function(m, scope, "cpp")
    for ref in c.findall("innerclass"):
        if ref.get("prot", "public") != "public":
            continue
        inner = load_compound(xml_dir, ref.get("refid"))
        if inner is not None and inner.get("id") not in done:
            sub, n = render_class(xml_dir, inner, loc, done, level + 1)
            out += sub
            count += n
    return out, count


def process_header(xml_path, xml_dir):
    root = ET.parse(xml_path).getroot()
    cd = root.find("compounddef")
    if cd is None or cd.get("kind") != "file":
        return None
    loc = cd.find("location").get("file", "")
    if not loc.endswith(HEADER_SUFFIXES) or "internal" in loc:
        return None
    module = Path(loc).stem
    brief = " ".join(text(cd.find("briefdescription")).split())
    # headers are included by file name, the include dirs are set by the build
    lines = [f"# {module}  (`#include \"{Path(loc).name}\"`)", ""]
    if brief:
        lines += [brief, ""]
    for p in paras(cd.find("detaileddescription")):
        lines += [p, ""]

    other = render_other(cd)
    listing = text(cd.find("programlisting"))
    # plain C structs/unions declared in this header: fields with their comments
    c_structs = []
    for ref in cd.findall("innerclass"):
        c = load_compound(xml_dir, ref.get("refid"))
        if (c is not None and ref.get("prot", "public") == "public"
                and in_file(c, loc) and c.get("kind") in ("struct", "union")
                and "::" not in text(c.find("compoundname"))):
            c_structs.append(c)
    for c in c_structs:
        other += render_c_struct(c, listing)
    if other:
        lines += ["## Types and macros", ""] + other
    funcs = [m for m in cd.iter("memberdef") if m.get("kind") == "function"
             and m.get("prot", "public") == "public"]
    if funcs:
        lines += ["## Functions", ""]
        for m in funcs:
            lines += render_function(m)
    count = len(funcs)

    # C++: namespaces (free functions, enums, typedefs) and classes/structs of this header
    namespaces = collect_namespaces(xml_dir, cd)
    for ns in namespaces.values():
        ns_name = text(ns.find("compoundname")).strip()
        ns_other = render_other(ns, loc, "cpp")
        ns_funcs = [m for m in ns.iter("memberdef") if m.get("kind") == "function"
                    and m.get("prot", "public") == "public" and in_file(m, loc)]
        if ns_other or ns_funcs:
            lines += [f"## Namespace `{ns_name}`", ""] + ns_other
            for m in ns_funcs:
                lines += render_function(m, "", "cpp")
            count += len(ns_funcs)
    refs = list(cd.findall("innerclass"))
    for ns in namespaces.values():
        refs += ns.findall("innerclass")
    classes, ids = [], set()
    for ref in refs:
        if ref.get("prot", "public") != "public" or ref.get("refid") in ids:
            continue
        ids.add(ref.get("refid"))
        c = load_compound(xml_dir, ref.get("refid"))
        # plain C structs (global, not a class) keep their existing output;
        # Doxygen reports .h files as C++, so test the declaration instead
        if c is None or not in_file(c, loc):
            continue
        if c.get("kind") == "class" or "::" in text(c.find("compoundname")):
            classes.append(c)
    done = set()
    for c in classes:
        if c.get("id") in done:
            continue
        sub, n = render_class(xml_dir, c, loc, done)
        lines += sub
        count += n
    return module, loc, brief, "\n".join(lines).rstrip() + "\n", count


def fatal(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(2)


def header_location(xml_path):
    """Source path of the header described by a Doxygen file XML, or None."""
    try:
        cd = ET.parse(xml_path).getroot().find("compounddef")
    except ET.ParseError:
        return None
    if cd is None or cd.get("kind") != "file" or cd.find("location") is None:
        return None
    return cd.find("location").get("file", "")


def same_header(loc, arg):
    """True if the Doxygen location and the user supplied path are the same file."""
    try:
        if Path(loc).resolve() == Path(arg).resolve():
            return True
    except OSError:
        pass
    want = os.path.normpath(arg).replace(os.sep, "/")
    have = Path(loc).as_posix()
    # Doxygen may record the path relative to inc/ (STRIP_FROM_PATH)
    return have == want or have.endswith("/" + want) or want.endswith("/" + have)


def read_index_rows(index_path):
    """Rows of an existing INDEX.md as {module: (header, brief, n)}."""
    rows = {}
    if not index_path.is_file():
        return rows
    for line in index_path.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line)[1:-1]]
        if len(cells) == 4 and cells[0] not in ("Module", "--------"):
            rows[cells[0]] = (cells[1], cells[2], cells[3])
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("headers", nargs="*",
                    help="only generate these headers (e.g. inc/service/event_bus/ez_event_bus.h); "
                         "default: every public header")
    ap.add_argument("--xml", default="doxygen/xml", help="Doxygen XML output dir")
    ap.add_argument("--out", default="docs_llm/api", help="Output dir for markdown")
    ap.add_argument("--inc", default="inc", help="Public header root, used for the coverage check")
    args = ap.parse_args()

    xml_dir, out_dir, inc_dir = Path(args.xml), Path(args.out), Path(args.inc)
    if not xml_dir.is_dir():
        fatal(f"{xml_dir} not found (run doxygen with GENERATE_XML=YES)")

    xml_files = sorted(list(xml_dir.glob("*_8h.xml")) + list(xml_dir.glob("*_8hpp.xml")))
    partial = bool(args.headers)
    if partial:
        selected = []
        for h in args.headers:
            found = [f for f in xml_files
                     if (loc := header_location(f)) is not None and same_header(loc, h)]
            if not found:
                fatal(f"{h} not found in {xml_dir} (is it under INPUT in the Doxyfile, "
                      f"and was doxygen run after the last change?)")
            selected += found
    else:
        selected = xml_files

    results, names, failed = [], {}, []
    for f in selected:
        try:
            r = process_header(f, xml_dir)
        except Exception as e:  # a broken header must not stop the others
            failed.append(f"{f.name}: {type(e).__name__}: {e}")
            continue
        if not r:
            if partial:
                fatal(f"{f.name} is not a public header (.h/.hpp, not internal)")
            continue
        module, loc = r[0], r[1]
        if module in names:
            fatal(f"module name '{module}' is used by both {names[module]} and {loc}")
        names[module] = loc
        results.append(r)
    if not results:
        fatal("no public headers generated" + (f" ({'; '.join(failed)})" if failed else ""))

    out_dir.mkdir(parents=True, exist_ok=True)
    for module, loc, brief, md, _ in results:
        (out_dir / f"{module}.md").write_text(BANNER + "\n\n" + md, encoding="utf-8")

    # INDEX.md: keep the rows of untouched modules when only some headers were generated
    rows = read_index_rows(out_dir / "INDEX.md") if partial else {}
    for module, loc, brief, _, n in results:
        rows[module] = ("/".join(Path(loc).parts[-2:]), brief.replace("|", "\\|"), str(n))
    idx = [BANNER, "",
           "| Module | Header | Purpose | Functions |",
           "|--------|--------|---------|-----------|"]
    for module in sorted(rows):
        header, brief, n = rows[module]
        idx.append(f"| {module} | {header} | {brief} | {n} |")
    (out_dir / "INDEX.md").write_text("\n".join(idx) + "\n", encoding="utf-8")

    print(f"wrote {len(results)} module(s) to {out_dir}: "
          + ", ".join(r[0] for r in results))

    status = 0
    if failed:
        print(f"FAILED: {len(failed)} header(s) could not be processed:")
        for m in failed:
            print(f"  {m}")
        status = 1

    # coverage: every public header under --inc must have a cheat sheet (full run only)
    if not partial and inc_dir.is_dir():
        generated = {Path(loc).name for _, loc, _, _, _ in results}
        missing = sorted(str(p) for p in inc_dir.rglob("*")
                         if p.suffix in HEADER_SUFFIXES and p.name not in generated)
        if missing:
            print(f"MISSING: {len(missing)} header(s) under {inc_dir} have no cheat sheet:")
            for m in missing:
                print(f"  {m}")
            status = 1
    sys.exit(status)


if __name__ == "__main__":
    main()
